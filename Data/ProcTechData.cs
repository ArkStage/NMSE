    private static readonly Dictionary<string, uint> _bestSeeds = Data.BestSeeds;

    private sealed record Tables(
        Dictionary<string, StatInfo> StatTypes,
        float DefaultHitPoints,
        Dictionary<string, string> StatBaseTechs,
        Dictionary<string, Dictionary<string, float>> TechBonuses,
        Dictionary<string, uint> BestSeeds);

    private static Tables Unpack()
    {
        var raw = new byte[Packed.Length];
        for (int i = 0; i < raw.Length; i++)
            raw[i] = (byte)(Packed[i] ^ Mask[i & 15]);
        int at = 0;

        byte NextByte() => raw[at++];
        int NextInt()
        {
            int value = BitConverter.ToInt32(raw, at);
            at += 4;
            return value;
        }
        uint NextUInt()
        {
            uint value = BitConverter.ToUInt32(raw, at);
            at += 4;
            return value;
        }
        float NextFloat()
        {
            float value = BitConverter.ToSingle(raw, at);
            at += 4;
            return value;
        }
        string NextText()
        {
            int length = NextByte();
            var chars = new char[length];
            for (int i = 0; i < length; i++)
                chars[i] = (char)raw[at++];
            return new string(chars);
        }

        var statTypes = new Dictionary<string, StatInfo>(StringComparer.OrdinalIgnoreCase);
        int statTypeCount = NextInt();
        for (int i = 0; i < statTypeCount; i++)
        {
            string stat = NextText();
            string function = NextByte() switch { 0 => "Add", 1 => "Multiply", 2 => "Set", _ => "" };
            bool displayable = NextByte() != 0;
            statTypes[stat] = new StatInfo(function, displayable);
        }

        float defaultHitPoints = NextFloat();

        var statBaseTechs = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        int baseTechCount = NextInt();
        for (int i = 0; i < baseTechCount; i++)
            statBaseTechs[NextText()] = NextText();

        var techBonuses = new Dictionary<string, Dictionary<string, float>>(StringComparer.OrdinalIgnoreCase);
        int bonusCount = NextInt();
        for (int i = 0; i < bonusCount; i++)
        {
            string tech = NextText();
            int statCount = NextInt();
            var stats = new Dictionary<string, float>(StringComparer.OrdinalIgnoreCase);
            for (int s = 0; s < statCount; s++)
                stats[NextText()] = NextFloat();
            techBonuses[tech] = stats;
        }

        var bestSeeds = new Dictionary<string, uint>(StringComparer.OrdinalIgnoreCase);
        int seedCount = NextInt();
        for (int i = 0; i < seedCount; i++)
            bestSeeds[NextText()] = NextUInt();

        return new Tables(statTypes, defaultHitPoints, statBaseTechs, techBonuses, bestSeeds);
    }

    /// <summary>Returns the display function for a stat ("Add", "Multiply", "Set"), or null when unknown.</summary>
    public static string? GetStatFunction(string? statId) =>
        statId != null && _statTypes.TryGetValue(statId, out var info) && !string.IsNullOrEmpty(info.Function)
            ? info.Function
            : null;

    /// <summary>
    /// Whether the game shows this stat in the technology stat section. Unknown stats are
    /// treated as displayable.
    /// </summary>
    public static bool IsStatDisplayable(string? statId) =>
        statId == null || !_statTypes.TryGetValue(statId, out var info) || info.Displayable;

    /// <summary>
    /// Resolves the base stat amount for a displayed stat bonus. Returns 1 when no base is
    /// known.
    /// </summary>
    /// <param name="displayedStat">The stat being displayed (e.g. "Suit_Armour_Health").</param>
    /// <param name="itemBaseStat">The item technology's base stats type.</param>
    public static float GetBaseStatAmount(string? displayedStat, string? itemBaseStat)
    {
        TryGetBaseStatAmount(displayedStat, itemBaseStat, out float baseAmount);
        return baseAmount;
    }

    /// <summary>
    /// Resolves the base stat amount and reports whether the game data provided one
    /// (including an explicit base of 1). Add stats with a known base always display as a
    /// percentage of that base, matching the game.
    /// </summary>
    /// <param name="displayedStat">The stat being displayed (e.g. "Suit_Armour_Health").</param>
    /// <param name="itemBaseStat">The item technology's base stats type.</param>
    /// <param name="baseAmount">The resolved base amount (1 when unknown).</param>
    public static bool TryGetBaseStatAmount(string? displayedStat, string? itemBaseStat, out float baseAmount)
    {
        if (string.Equals(displayedStat, "Suit_Armour_Health", StringComparison.OrdinalIgnoreCase))
        {
            baseAmount = DefaultHitPoints;
            return true;
        }

        baseAmount = 1f;
        if (string.IsNullOrEmpty(itemBaseStat) || string.IsNullOrEmpty(displayedStat))
            return false;

        if (_statBaseTechs.TryGetValue(itemBaseStat, out string? baseTech)
            && _techBonuses.TryGetValue(baseTech, out var bonuses)
            && bonuses.TryGetValue(displayedStat, out float bonus) && bonus > 0f)
        {
            baseAmount = bonus;
            return true;
        }
        return false;
    }

    /// <summary>Returns the precomputed best ("god roll") seed for a procedural template.</summary>
    public static bool TryGetBestSeed(string? templateId, out uint seed)
    {
        seed = 0;
        return !string.IsNullOrEmpty(templateId) && _bestSeeds.TryGetValue(templateId, out seed);
    }
